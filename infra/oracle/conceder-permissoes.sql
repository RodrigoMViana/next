-- =============================================================================
-- Permissões dos usuários de aplicação (executar após as migrações Flyway)
-- Registros de governança são somente inclusão: sem UPDATE/DELETE (Arquitetura 7.3, RN05, RN24).
-- =============================================================================

-- Tabelas de negócio do módulo Configuração (leitura e escrita; nunca DELETE — RN04)
BEGIN
  FOR t IN (SELECT table_name FROM all_tables WHERE owner = 'NEXT_CONFIGURACAO'
             AND table_name NOT IN ('CONTRATADA_ALTERACAO', 'CONTRATO_ADITIVO', 'HISTORICO_ALTERACAO',
                                    'EVENTO_PROCESSADO', 'CHAVE_IDEMPOTENCIA', 'flyway_schema_history')) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON NEXT_CONFIGURACAO.' || t.table_name || ' TO NEXT_CONFIGURACAO_APP';
  END LOOP;
END;
/
-- Coleções filhas substituídas na edição (itens, expediente, feriados, regras de rascunho, vínculos)
GRANT DELETE ON NEXT_CONFIGURACAO.CONTRATO_ITEM TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.CONTRATO_FONTE TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.CONTRATO_SISTEMA TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.CALENDARIO_EXPEDIENTE TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.CALENDARIO_FERIADO TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.SLA_REGRA TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.SLA_SERVICO TO NEXT_CONFIGURACAO_APP;
GRANT DELETE ON NEXT_CONFIGURACAO.SLA_SISTEMA TO NEXT_CONFIGURACAO_APP;

-- Registros imutáveis: somente SELECT e INSERT
GRANT SELECT, INSERT ON NEXT_CONFIGURACAO.CONTRATADA_ALTERACAO TO NEXT_CONFIGURACAO_APP;
GRANT SELECT, INSERT ON NEXT_CONFIGURACAO.CONTRATO_ADITIVO TO NEXT_CONFIGURACAO_APP;
GRANT SELECT, INSERT ON NEXT_CONFIGURACAO.HISTORICO_ALTERACAO TO NEXT_CONFIGURACAO_APP;
GRANT SELECT, INSERT ON NEXT_CONFIGURACAO.EVENTO_PROCESSADO TO NEXT_CONFIGURACAO_APP;
GRANT SELECT, INSERT ON NEXT_CONFIGURACAO.CHAVE_IDEMPOTENCIA TO NEXT_CONFIGURACAO_APP;

-- BFF: trilha append-only; exportações com atualização de situação
GRANT SELECT, INSERT ON NEXT_AUDIT.TRILHA_ACESSO TO NEXT_AUDIT_APP;
GRANT SELECT, INSERT, UPDATE ON NEXT_AUDIT.EXPORTACAO TO NEXT_AUDIT_APP;

