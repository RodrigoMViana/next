#!/bin/bash
# Cria os esquemas do Next no PDB FREEPDB1 (container gvenzl/oracle-free).
# Cada módulo tem esquema e usuário de banco exclusivos (Arquitetura 7.1).
sqlplus -s "sys/${ORACLE_PASSWORD}@//localhost/FREEPDB1 as sysdba" <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE USER NEXT_CONFIGURACAO IDENTIFIED BY "${NEXT_CONFIGURACAO_SENHA}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO NEXT_CONFIGURACAO;
CREATE USER NEXT_AUDIT IDENTIFIED BY "${NEXT_AUDIT_SENHA}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO NEXT_AUDIT;
EXIT
SQL
